#include <stdio.h>

/*
 * 7-15 数列求和 —— 版本 4：公式法（不用循环，一步算出）
 *
 * 把通项展开：(k-2)(k-1)k = k^3 - 3k^2 + 2k
 * 再套三个求和公式 Σk^3、Σk^2、Σk，整理后得到一个闭式：
 *
 *     前 n 项和 = n * (n+1) * (n-1) * (n-2) / 4
 *
 * 验证：
 *   n=3 -> 3*4*2*1/4 = 6
 *   n=4 -> 4*5*3*2/4 = 30
 *   n=5 -> 5*6*4*3/4 = 90
 *
 * 这就是循环版一直累加的那个数。循环做 n 次乘法，公式只做 4 次乘法。
 *
 * 唯一要小心的还是溢出：n*(n+1) 还算安全，
 * 但再乘下去就超 int 了，所以第一个因子必须先转 long long。
 */
int main(void)
{
    int n;

    scanf("%d", &n);

    printf("%lld\n", (long long)n * (n + 1) * (n - 1) * (n - 2) / 4);
    return 0;
}
