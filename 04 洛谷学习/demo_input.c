#include<stdio.h>

/* ==========================================================
   输入演示：先读"个数"，再用 while 循环逐个读数
   这份代码只做一件事：把你输入的数，原样吐出来
   ========================================================== */
int main()
{
    int count = 0;   /* 第一行输入：后面有几个数 */
    int x = 0;       /* 当前读到的那个数（用完就扔，只装一个） */
    int i = 0;       /* 计数器：已经读了几个（从 0 开始数） */

    /* 第 1 个 scanf：从输入队列领走第一个数，装进 count */
    scanf("%d", &count);

    /* 守门员：还没读够 count 个，就继续转 */
    while (i < count) {

        /* 每转一圈，scanf 就从队列领走"下一个"数装进 x */
        scanf("%d", &x);

        /* 打印验证：左边是"第几个"，右边是"读到的值" */
        printf("%d -> %d\n", i + 1, x);

        /* 发动机：i 加 1。删掉这行就是死循环，试试！ */
        i = i + 1;
    }

    return 0;
}
